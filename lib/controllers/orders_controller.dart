import 'package:flutter/foundation.dart';
import '../core/services/storage_service.dart';
import '../core/services/supabase_service.dart';
import '../models/order_model.dart';
import '../models/cart_item_model.dart';
import '../models/waiter_call_model.dart';

/// Controller handling customer order placement, live tracking,
/// merchant KDS kitchen display status advancement, and waiter call alerts.
class OrdersController extends ChangeNotifier {
  final SupabaseService _supabaseService;
  final StorageService? _storageService;

  List<OrderModel> _orders = [];
  OrderModel? _activeOrder;
  List<WaiterCallModel> _activeWaiterCalls = [];
  bool _isLoading = false;
  bool _isSubmitting = false;
  String? _errorMessage;

  OrdersController({
    required SupabaseService supabaseService,
    StorageService? storageService,
  })  : _supabaseService = supabaseService,
        _storageService = storageService;

  List<OrderModel> get orders => _orders;
  OrderModel? get activeOrder => _activeOrder;
  List<WaiterCallModel> get activeWaiterCalls => _activeWaiterCalls;
  bool get isLoading => _isLoading;
  bool get isSubmitting => _isSubmitting;
  String? get errorMessage => _errorMessage;

  /// Loads orders scoped strictly to the current store (Tenant Isolation)
  Future<void> loadOrdersForStore(String storeId) async {
    _isLoading = true;
    _errorMessage = null;
    notifyListeners();

    try {
      _orders = await _supabaseService.fetchOrdersByStoreId(storeId);
      await loadActiveWaiterCalls(storeId);
    } catch (e) {
      _errorMessage = 'Failed to load orders: $e';
    } finally {
      _isLoading = false;
      notifyListeners();
    }
  }

  /// Places a customer order from cart items
  Future<OrderModel?> placeCartOrder({
    required String storeId,
    required String tableNumber,
    required String customerName,
    required String customerPhone,
    required List<CartItemModel> cartItems,
    required double totalAmount,
    required String paymentMethod, // 'cash' or 'advance'
  }) async {
    _isSubmitting = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final serializedItems = cartItems.map((ci) => ci.toJson()).toList();

      final newOrder = OrderModel(
        id: '', // Generated by Supabase backend / mock
        storeId: storeId,
        customerName: customerName,
        customerPhone: customerPhone,
        deliveryAddress: 'Table $tableNumber - Dine In',
        totalAmount: totalAmount,
        orderType: 'delivery',
        status: 'pending',
        tableNumber: tableNumber,
        items: serializedItems,
        paymentMethod: paymentMethod,
        paymentStatus: paymentMethod == 'advance' ? 'paid' : 'unpaid',
        createdAt: DateTime.now(),
      );

      final created = await _supabaseService.createOrder(newOrder);
      _orders.insert(0, created);
      _activeOrder = created;

      if (_storageService != null) {
        await _storageService.saveActiveOrderId(created.id);
      }

      return created;
    } catch (e) {
      _errorMessage = 'Failed to submit order: $e';
      return null;
    } finally {
      _isSubmitting = false;
      notifyListeners();
    }
  }

  /// Compatibility helper for placing a single item order
  Future<OrderModel?> placeOrder({
    required String storeId,
    required String customerName,
    required String customerPhone,
    String? deliveryAddress,
    required double totalAmount,
    required String orderType,
    String tableNumber = '01',
    String paymentMethod = 'cash',
  }) async {
    _isSubmitting = true;
    _errorMessage = null;
    notifyListeners();

    try {
      final newOrder = OrderModel(
        id: '',
        storeId: storeId,
        customerName: customerName,
        customerPhone: customerPhone,
        deliveryAddress: deliveryAddress ?? 'Table $tableNumber - Dine In',
        totalAmount: totalAmount,
        orderType: orderType,
        status: 'pending',
        tableNumber: tableNumber,
        items: [],
        paymentMethod: paymentMethod,
        paymentStatus: paymentMethod == 'advance' ? 'paid' : 'unpaid',
        createdAt: DateTime.now(),
      );

      final created = await _supabaseService.createOrder(newOrder);
      _orders.insert(0, created);
      _activeOrder = created;
      if (_storageService != null) {
        await _storageService.saveActiveOrderId(created.id);
      }
      return created;
    } catch (e) {
      _errorMessage = 'Failed to submit order: $e';
      return null;
    } finally {
      _isSubmitting = false;
      notifyListeners();
    }
  }

  /// Refreshes the currently tracked order for the TrackingScreen
  Future<void> refreshActiveOrder([String? orderId]) async {
    final targetId = orderId ?? _activeOrder?.id ?? _storageService?.getActiveOrderId();
    if (targetId == null || targetId.isEmpty) return;

    try {
      final updated = await _supabaseService.fetchOrderById(targetId);
      _activeOrder = updated;
      notifyListeners();
    } catch (e) {
      debugPrint('[OrdersController] Error refreshing active order: $e');
    }
  }

  /// Advances order status in the Merchant KDS Dashboard
  /// (Pending ➔ Preparing ➔ Ready ➔ Delivered)
  Future<bool> advanceOrderStatus(String orderId, String nextStatus) async {
    try {
      final updated = await _supabaseService.updateOrderStatus(orderId, nextStatus);
      final index = _orders.indexWhere((o) => o.id == orderId);
      if (index != -1) {
        _orders[index] = updated;
      }
      if (_activeOrder?.id == orderId) {
        _activeOrder = updated;
      }
      notifyListeners();
      return true;
    } catch (e) {
      _errorMessage = 'Failed to update order status: $e';
      notifyListeners();
      return false;
    }
  }

  /// Triggers "Call Waiter" from customer table
  Future<bool> triggerWaiterCall({
    required String storeId,
    required String tableNumber,
  }) async {
    try {
      final call = await _supabaseService.callWaiter(storeId, tableNumber);
      _activeWaiterCalls.insert(0, call);
      notifyListeners();
      return true;
    } catch (e) {
      debugPrint('[OrdersController] Error calling waiter: $e');
      return false;
    }
  }

  /// Loads pending waiter calls for Merchant KDS panel
  Future<void> loadActiveWaiterCalls(String storeId) async {
    try {
      _activeWaiterCalls = await _supabaseService.fetchActiveWaiterCalls(storeId);
      notifyListeners();
    } catch (e) {
      debugPrint('[OrdersController] Error loading waiter calls: $e');
    }
  }

  /// Dismisses / marks resolved a waiter call
  Future<void> resolveWaiterCall(String callId) async {
    try {
      await _supabaseService.resolveWaiterCall(callId);
      _activeWaiterCalls.removeWhere((c) => c.id == callId);
      notifyListeners();
    } catch (e) {
      debugPrint('[OrdersController] Error resolving waiter call: $e');
    }
  }

  void clear() {
    _orders = [];
    _activeOrder = null;
    _activeWaiterCalls = [];
    _isLoading = false;
    _isSubmitting = false;
    _errorMessage = null;
    notifyListeners();
  }
}
